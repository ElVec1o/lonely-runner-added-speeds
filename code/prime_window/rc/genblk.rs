// rc/genblk.rs : block certificate for  T <= #primes in [N+1+N/2, 2N],  LO <= N <= N1.
// usage: genblk T LO N1 TAG OUTFILE   (TAG names the theorems blkTAG_i and the final theorem)
// stats-only if OUTFILE == "-"
use std::env; use std::fs::File; use std::io::Write;
fn main(){
    let a:Vec<String>=env::args().collect();
    let t:usize=a[1].parse().unwrap(); let lo0:usize=a[2].parse().unwrap();
    let n1:usize=a[3].parse().unwrap(); let tag=&a[4]; let out=&a[5];
    let lim=2*n1+10;
    let mut is=vec![true;lim+1]; is[0]=false; is[1]=false;
    let mut i=2; while i*i<=lim { if is[i]{ let mut j=i*i; while j<=lim {is[j]=false;j+=i;} } i+=1; }
    let mut blocks:Vec<(usize,usize,Vec<usize>)>=vec![];
    let mut lo=lo0;
    while lo<=n1 {
        let mut ps:Vec<usize>=vec![]; let mut p=2*lo;
        while ps.len()<t { if is[p]{ps.push(p);} p-=1; }
        ps.reverse(); let pmin=ps[0];
        let mut hi=lo; while (hi+1)+1+(hi+1)/2<=pmin { hi+=1; }
        assert!(pmin>=lo+1+lo/2,"block empty at {}",lo);
        blocks.push((lo,hi,ps)); lo=hi+1;
    }
    println!("T={} lo0={} N1={}: {} blocks, last hi {}",t,lo0,n1,blocks.len(),blocks.last().unwrap().1);
    if out=="-" {return;}
    let mut s=String::new();
    s.push_str(&format!("/- GENERATED by the block generator `genblk.rs` of the accompanying code (T = {}, N from {} to {}). Do not edit.\n   {} blocks; block i: {} primes p in [hi+1+hi/2, 2 lo] settle every N in [lo, hi]. -/\nimport LRSpectrumFull.Sext6.Gap.RobustCorA\n\nnamespace LRSpectrumFull\nnamespace Sext6\nnamespace Gap\n\n",t,lo0,n1,blocks.len(),t));
    for (k,(lo,hi,ps)) in blocks.iter().enumerate() {
        let l=ps.iter().map(|x|x.to_string()).collect::<Vec<_>>().join(", ");
        let alts=vec!["rfl";t].join(" | ");
        s.push_str(&format!("theorem blk{}_{} {{N : ℕ}} (h1 : {} ≤ N) (h2 : N ≤ {}) :\n    {} ≤ ((Finset.Icc (N + 1 + N / 2) (2 * N)).filter Nat.Prime).card :=\n  winK [{}] (by decide) (by decide)\n    (by intro p hp; simp only [List.mem_cons, List.not_mem_nil, or_false] at hp\n        rcases hp with {} <;> norm_num)\n    (by intro p hp; simp only [List.mem_cons, List.not_mem_nil, or_false] at hp\n        rcases hp with {} <;> omega)\n    (by intro p hp; simp only [List.mem_cons, List.not_mem_nil, or_false] at hp\n        rcases hp with {} <;> omega)\n\n",tag,k,lo,hi,t,l,alts,alts,alts));
    }
    s.push_str(&format!("theorem window{}_small {{N : ℕ}} (h1 : {} ≤ N) (h2 : N ≤ {}) :\n    {} ≤ ((Finset.Icc (N + 1 + N / 2) (2 * N)).filter Nat.Prime).card := by\n",tag,lo0,n1,t));
    for (k,(_lo,hi,_)) in blocks.iter().enumerate() {
        if k+1==blocks.len(){ s.push_str(&format!("  exact blk{}_{} (by omega) (by omega)\n",tag,k)); }
        else { s.push_str(&format!("  by_cases c{} : N ≤ {}\n  · exact blk{}_{} (by omega) c{}\n",k,hi,tag,k,k)); }
    }
    s.push_str("\nend Gap\nend Sext6\nend LRSpectrumFull\n");
    File::create(out).unwrap().write_all(s.as_bytes()).unwrap();
}
