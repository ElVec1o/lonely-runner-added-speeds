// rc2/genblk3.rs : block certificates (shared prime table) for  T <= #primes in [N+1+N/2, 2N],  LO <= N <= N1.
// usage: genblk3 K T LO N1 PERMOD OUTDIR      (PERMOD = blocks per module; "-" as OUTDIR = stats only)
// Per module: PL = all primes from the first block's p_min to 2*lo_last, as segments of <= 40 (norm_num each, prime_append),
// PL.Nodup from AscB (linear strict-ascent test, kernel decide); block i = T consecutive entries PL[idx..idx+T) (winK3), bounds by kernel decide.
// The LAST part also proves primeWin{K}_mid : LO <= N <= N1 -> forall r, 2r<=N -> PrimeWin K N r.
use std::env; use std::fs::File; use std::io::Write;
fn main(){
    let a:Vec<String>=env::args().collect();
    let kk:usize=a[1].parse().unwrap(); let t:usize=a[2].parse().unwrap();
    let lo0:usize=a[3].parse().unwrap(); let n1:usize=a[4].parse().unwrap();
    let permod:usize=a[5].parse().unwrap(); let outdir=&a[6];
    let lim=2*n1+10;
    let mut is=vec![true;lim+1]; is[0]=false; is[1]=false;
    let mut i=2; while i*i<=lim { if is[i]{ let mut j=i*i; while j<=lim {is[j]=false;j+=i;} } i+=1; }
    let mut blocks:Vec<(usize,usize,Vec<usize>)>=vec![];
    let mut lo=lo0;
    while lo<=n1 {
        let mut ps:Vec<usize>=vec![]; let mut p=2*lo;
        while ps.len()<t { if is[p]{ps.push(p);} p-=1; }
        ps.reverse(); let pmin=ps[0];
        let mut hi=lo; while (hi+1)+1+(hi+1)/2<=pmin { hi+=1; }
        assert!(pmin>=lo+1+lo/2,"block empty at {}",lo);
        blocks.push((lo,hi,ps)); lo=hi+1;
    }
    let nb=blocks.len(); let np=(nb+permod-1)/permod;
    println!("K={} T={} lo0={} N1={}: {} blocks in {} parts, last hi {}",kk,t,lo0,n1,nb,np,blocks.last().unwrap().1);
    if outdir=="-" {return;}
    for j in 0..np {
        let part=&blocks[j*permod..std::cmp::min(nb,(j+1)*permod)];
        let plo=part[0].0; let phi=part.last().unwrap().1;
        let pfirst=part[0].2[0]; let plast=*part.last().unwrap().2.last().unwrap();
        let pl:Vec<usize>=(pfirst..=plast).filter(|&x| is[x]).collect();
        let segs:Vec<&[usize]>=pl.chunks(40).collect();
        let ns=segs.len();
        let nm=format!("PL{}p{}",kk,j);
        let mut s=String::new();
        s.push_str(&format!("/- GENERATED by the block generator `genblk3.rs` of the accompanying code (K = {}, T = {}, N from {} to {}, part {} of {}). Do not edit.\n   Block i: T consecutive primes of the table {} (all {} primes in [{}, {}]) lie in [hi+1+hi/2, 2 lo] and settle every N in [lo, hi].\n   This part covers N in [{}, {}]. -/\nimport LRSpectrumFull.Sext6.Gap.RobustKGen\n",kk,t,lo0,n1,j,np,nm,pl.len(),pfirst,plast,plo,phi));
        if j+1==np { for jj in 0..j { s.push_str(&format!("import LRSpectrumFull.Sext6.Gap.RobustKBlk{}p{}\n",kk,jj)); } }
        s.push_str("\nnamespace LRSpectrumFull\nnamespace Sext6\nnamespace Gap\n\n");
        for (si,sg) in segs.iter().enumerate() {
            let l=sg.iter().map(|x|x.to_string()).collect::<Vec<_>>().join(", ");
            s.push_str(&format!("def S{nm}_{si} : List ℕ := [{l}]\n\ntheorem pS{nm}_{si} : ∀ p ∈ S{nm}_{si}, p.Prime := by\n  unfold S{nm}_{si}\n  norm_num\n\n",nm=nm,si=si,l=l));
        }
        let names:Vec<String>=(0..ns).map(|si| format!("S{}_{}",nm,si)).collect();
        s.push_str(&format!("def {} : List ℕ := {}\n\n",nm,names.join(" ++ ")));
        let mut pe=format!("pS{}_0",nm);
        for si in 1..ns { pe=format!("prime_append ({}) pS{}_{}",pe,nm,si); }
        s.push_str(&format!("theorem {nm}_prime : ∀ p ∈ {nm}, p.Prime := by\n  unfold {nm}\n  exact {pe}\n\ntheorem {nm}_nodup : {nm}.Nodup :=\n  AscB_nodup (by decide +kernel)\n\n",nm=nm,pe=pe));
        for (i,(blo,bhi,ps)) in part.iter().enumerate() {
            let idx=pl.iter().position(|&x| x==ps[0]).unwrap();
            assert!(pl[idx..idx+t]==ps[..]);
            let pa=ps[0]; let pb=*ps.last().unwrap();
            s.push_str(&format!("theorem blk{k}p{j}_{i} {{N : ℕ}} (h1 : {blo} ≤ N) (h2 : N ≤ {bhi}) :\n    {t} ≤ ((Finset.Icc (N + 1 + N / 2) (2 * N)).filter Nat.Prime).card :=\n  winK3 {nm} {idx} {pa} {pb} {nm}_nodup {nm}_prime (by decide +kernel) (by decide +kernel)\n    (by decide +kernel) (by omega) (by omega)\n\n",k=kk,j=j,i=i,blo=blo,bhi=bhi,t=t,nm=nm,idx=idx,pa=pa,pb=pb));
        }
        s.push_str(&format!("theorem win{k}p{j} {{N : ℕ}} (h1 : {plo} ≤ N) (h2 : N ≤ {phi}) :\n    {t} ≤ ((Finset.Icc (N + 1 + N / 2) (2 * N)).filter Nat.Prime).card := by\n",k=kk,j=j,plo=plo,phi=phi,t=t));
        for (i,(_blo,bhi,_)) in part.iter().enumerate() {
            if i+1==part.len(){ s.push_str(&format!("  exact blk{}p{}_{} (by omega) (by omega)\n",kk,j,i)); }
            else { s.push_str(&format!("  by_cases c{i} : N ≤ {bhi}\n  · exact blk{k}p{j}_{i} (by omega) c{i}\n",i=i,bhi=bhi,k=kk,j=j)); }
        }
        if j+1==np {
            s.push_str(&format!("\n/-- `PrimeWin {k} N r` for `{lo0} ≤ N ≤ {n1}` and every `r` with `2 r ≤ N`: UNCONDITIONAL. -/\ntheorem primeWin{k}_mid {{N : ℕ}} (h1 : {lo0} ≤ N) (h2 : N ≤ {n1}) :\n    ∀ r : ℕ, 2 * r ≤ N → PrimeWin {k} N r := by\n  have h : {t} ≤ ((Finset.Icc (N + 1 + N / 2) (2 * N)).filter Nat.Prime).card := by\n",k=kk,lo0=lo0,n1=n1,t=t));
            for jj in 0..np {
                let pp=&blocks[jj*permod..std::cmp::min(nb,(jj+1)*permod)];
                let ph=pp.last().unwrap().1;
                if jj+1==np { s.push_str(&format!("    exact win{}p{} (by omega) (by omega)\n",kk,jj)); }
                else { s.push_str(&format!("    by_cases d{jj} : N ≤ {ph}\n    · exact win{k}p{jj} (by omega) d{jj}\n",jj=jj,ph=ph,k=kk)); }
            }
            s.push_str("  exact primeWin_of_window (by omega) (by omega)\n");
        }
        s.push_str("\nend Gap\nend Sext6\nend LRSpectrumFull\n");
        let path=format!("{}/RobustKBlk{}p{}.lean",outdir,kk,j);
        File::create(&path).unwrap().write_all(s.as_bytes()).unwrap();
        println!("PART {} {} N[{},{}] blocks {} table {} primes in {} segments",path,j,plo,phi,part.len(),pl.len(),ns);
    }
}
