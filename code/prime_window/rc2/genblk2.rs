// rc2/genblk2.rs : block certificates for  T <= #primes in [N+1+N/2, 2N],  LO <= N <= N1  (T = 3K(K+1)+1 passed explicitly).
// usage: genblk2 K T LO N1 PERMOD OUTDIR      (PERMOD = blocks per module; "-" as OUTDIR = stats only)
// writes OUTDIR/RobustKBlk{K}p{J}.lean; the LAST part also proves primeWin{K}_mid : LO <= N <= N1 -> forall r, 2r<=N -> PrimeWin K N r.
// Block form: winK2 ps a b (Nodup) (len) (all >= a) (all <= b) (all prime) (N+1+N/2 <= a) (b <= 2N), kernel `decide` for list facts.
use std::env; use std::fs::File; use std::io::Write;
fn main(){
    let a:Vec<String>=env::args().collect();
    let kk:usize=a[1].parse().unwrap(); let t:usize=a[2].parse().unwrap();
    let lo0:usize=a[3].parse().unwrap(); let n1:usize=a[4].parse().unwrap();
    let permod:usize=a[5].parse().unwrap(); let outdir=&a[6];
    let lim=2*n1+10;
    let mut is=vec![true;lim+1]; is[0]=false; is[1]=false;
    let mut i=2; while i*i<=lim { if is[i]{ let mut j=i*i; while j<=lim {is[j]=false;j+=i;} } i+=1; }
    let mut blocks:Vec<(usize,usize,Vec<usize>)>=vec![];
    let mut lo=lo0;
    while lo<=n1 {
        let mut ps:Vec<usize>=vec![]; let mut p=2*lo;
        while ps.len()<t { if is[p]{ps.push(p);} p-=1; }
        ps.reverse(); let pmin=ps[0];
        let mut hi=lo; while (hi+1)+1+(hi+1)/2<=pmin { hi+=1; }
        assert!(pmin>=lo+1+lo/2,"block empty at {}",lo);
        blocks.push((lo,hi,ps)); lo=hi+1;
    }
    let nb=blocks.len(); let np=(nb+permod-1)/permod;
    println!("K={} T={} lo0={} N1={}: {} blocks in {} parts, last hi {}",kk,t,lo0,n1,nb,np,blocks.last().unwrap().1);
    if outdir=="-" {return;}
    for j in 0..np {
        let part=&blocks[j*permod..std::cmp::min(nb,(j+1)*permod)];
        let plo=part[0].0; let phi=part.last().unwrap().1;
        let mut s=String::new();
        s.push_str(&format!("/- GENERATED by the block generator `genblk2.rs` of the accompanying code (K = {}, T = {}, N from {} to {}, part {} of {}). Do not edit.\n   Block i: T primes in [hi+1+hi/2, 2 lo] settle every N in [lo, hi]. This part covers N in [{}, {}]. -/\nimport LRSpectrumFull.Sext6.Gap.RobustKGen\n",kk,t,lo0,n1,j,np,plo,phi));
        if j+1==np { for jj in 0..j { s.push_str(&format!("import LRSpectrumFull.Sext6.Gap.RobustKBlk{}p{}\n",kk,jj)); } }
        s.push_str("\nnamespace LRSpectrumFull\nnamespace Sext6\nnamespace Gap\n\n");
        for (i,(blo,bhi,ps)) in part.iter().enumerate() {
            let l=ps.iter().map(|x|x.to_string()).collect::<Vec<_>>().join(", ");
            let alts=vec!["rfl";t].join(" | ");
            let pa=ps[0]; let pb=*ps.last().unwrap();
            s.push_str(&format!("theorem blk{k}p{j}_{i} {{N : ℕ}} (h1 : {blo} ≤ N) (h2 : N ≤ {bhi}) :\n    {t} ≤ ((Finset.Icc (N + 1 + N / 2) (2 * N)).filter Nat.Prime).card :=\n  winK2 [{l}] {pa} {pb} (by decide +kernel) (by decide +kernel) (by decide +kernel) (by decide +kernel)\n    (by first\n        | (norm_num; done)\n        | (intro p hp; simp only [List.mem_cons, List.not_mem_nil, or_false] at hp; rcases hp with {alts} <;> norm_num))\n    (by omega) (by omega)\n\n",k=kk,j=j,i=i,blo=blo,bhi=bhi,t=t,l=l,pa=pa,pb=pb,alts=alts));
        }
        s.push_str(&format!("theorem win{k}p{j} {{N : ℕ}} (h1 : {plo} ≤ N) (h2 : N ≤ {phi}) :\n    {t} ≤ ((Finset.Icc (N + 1 + N / 2) (2 * N)).filter Nat.Prime).card := by\n",k=kk,j=j,plo=plo,phi=phi,t=t));
        for (i,(_blo,bhi,_)) in part.iter().enumerate() {
            if i+1==part.len(){ s.push_str(&format!("  exact blk{}p{}_{} (by omega) (by omega)\n",kk,j,i)); }
            else { s.push_str(&format!("  by_cases c{i} : N ≤ {bhi}\n  · exact blk{k}p{j}_{i} (by omega) c{i}\n",i=i,bhi=bhi,k=kk,j=j)); }
        }
        if j+1==np {
            s.push_str(&format!("\n/-- `PrimeWin {k} N r` for `{lo0} ≤ N ≤ {n1}` and every `r` with `2 r ≤ N`: UNCONDITIONAL. -/\ntheorem primeWin{k}_mid {{N : ℕ}} (h1 : {lo0} ≤ N) (h2 : N ≤ {n1}) :\n    ∀ r : ℕ, 2 * r ≤ N → PrimeWin {k} N r := by\n  have h : {t} ≤ ((Finset.Icc (N + 1 + N / 2) (2 * N)).filter Nat.Prime).card := by\n",k=kk,lo0=lo0,n1=n1,t=t));
            for jj in 0..np {
                let pp=&blocks[jj*permod..std::cmp::min(nb,(jj+1)*permod)];
                let ph=pp.last().unwrap().1;
                if jj+1==np { s.push_str(&format!("    exact win{}p{} (by omega) (by omega)\n",kk,jj)); }
                else { s.push_str(&format!("    by_cases d{jj} : N ≤ {ph}\n    · exact win{k}p{jj} (by omega) d{jj}\n",jj=jj,ph=ph,k=kk)); }
            }
            s.push_str(&format!("  exact primeWin_of_window (by omega) (by omega)\n"));
        }
        s.push_str("\nend Gap\nend Sext6\nend LRSpectrumFull\n");
        let path=format!("{}/RobustKBlk{}p{}.lean",outdir,kk,j);
        File::create(&path).unwrap().write_all(s.as_bytes()).unwrap();
        println!("PART {} {} N[{},{}] blocks {}",path,j,plo,phi,part.len());
    }
}
