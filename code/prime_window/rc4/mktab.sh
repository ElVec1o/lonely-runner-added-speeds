#!/bin/bash
# usage: mktab.sh KMAX > RobustK13Tab.lean   (needs ktab.txt: k T Nstar Mtab ; logs/gen$k.out for the number of parts)
KMAX=$1
D="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cat <<EOT
/-
# Theorem S, hypothesis-free from the exact sieve threshold \`N*(k)\`, \`13 ≤ k ≤ $KMAX\`

For \`13 ≤ k ≤ $KMAX\`: sieve blocks (\`FinBlk{k}p{j}\`, generated by \`rc4/genblk5.rs\`, kernel-checked) give
\`PrimeWin k N r\` for \`N*(k) ≤ N ≤ MCheb k - 1\`, and \`RobustK13Cheb.copWin_cheb_table\` gives \`CopWin k N r\` for \`N ≥ MCheb k\`.
\`N*(k)\` = least \`N\` such that every \`N' ≥ N\` has at least \`T = 3k(k+1)+1\` primes in \`[N'+1+N'/2, 2N']\`
(exact sieve, \`rc4/thr2.rs\`).

* \`NstarX k\`            : \`N*(k)\` for \`13 ≤ k ≤ $KMAX\`.
* \`copWin_ext\`          : \`13 ≤ k ≤ $KMAX\`, \`N*(k) ≤ N\` ⟹ \`CopWin k N r\`.
* \`copWin_all\`          : \`1 ≤ k ≤ $KMAX\`, \`NstarAll k ≤ N\` ⟹ \`CopWin k N r\` (\`NstarAll = Nstar\` for \`k ≤ 12\`).
* \`theoremS_all\`, \`cor_a_all\` : Theorem S and Corollary S'(a), no hypothesis, \`1 ≤ k ≤ $KMAX\`, \`N ≥ N*(k)\`.
No \`sorry\`, no \`axiom\`.
-/
import LRSpectrumFull.Sext6.Gap.RobustK13Cheb
EOT
while read k t lo m; do
  [ $k -le $KMAX ] || continue
  np=$(grep -o "in [0-9]* parts" $D/logs/gen$k.out | head -1 | awk '{print $2}')
  echo "import LRSpectrumFull.Sext6.Gap.FinBlk${k}p$((np-1))"
done < $D/ktab.txt
cat <<EOT

namespace LRSpectrumFull
namespace Sext6
namespace Gap

/-- The exact sieve threshold \`N*(k)\`, \`13 ≤ k ≤ $KMAX\`. -/
def NstarX : ℕ → ℕ
EOT
while read k t lo m; do [ $k -le $KMAX ] || continue; echo "  | $k => $lo"; done < $D/ktab.txt
echo "  | _ => 0"
cat <<EOT

theorem copWin_ext {k N r : ℕ} (hk1 : 13 ≤ k) (hk2 : k ≤ $KMAX) (hN : NstarX k ≤ N)
    (hr1 : 1 ≤ r) (hr : 2 * r ≤ N) : CopWin k N r := by
  interval_cases k
EOT
while read k t lo m; do [ $k -le $KMAX ] || continue; cat <<EOT
  · have h : $lo ≤ N := by simpa [NstarX] using hN
    by_cases h1 : N ≤ $((m-1))
    · exact copWin_of_primeWin hr1 (primeWinF${k}_mid h h1 r hr)
    · exact copWin_cheb_table (by norm_num) (by norm_num) (by simp [MCheb]; omega) hr1 hr
EOT
done < $D/ktab.txt
cat <<EOT

/-- \`N*(k)\`, \`1 ≤ k ≤ $KMAX\`. -/
def NstarAll (k : ℕ) : ℕ := if k ≤ 12 then Nstar k else NstarX k

theorem copWin_all {k N r : ℕ} (hk1 : 1 ≤ k) (hk2 : k ≤ $KMAX) (hN : NstarAll k ≤ N)
    (hr1 : 1 ≤ r) (hr : 2 * r ≤ N) : CopWin k N r := by
  by_cases h12 : k ≤ 12
  · have h : Nstar k ≤ N := by simpa [NstarAll, h12] using hN
    exact copWin_table hk1 h12 h hr1 hr
  · have h : NstarX k ≤ N := by simpa [NstarAll, h12] using hN
    exact copWin_ext (by omega) hk2 h hr1 hr

/-- **Theorem S, no hypothesis, \`1 ≤ k ≤ $KMAX\`, every \`N ≥ N*(k)\`.** -/
theorem theoremS_all {n k N r : ℕ} (hk1 : 1 ≤ k) (hk2 : k ≤ $KMAX) (hN : NstarAll k ≤ N)
    (hr1 : 1 ≤ r) (hr : 2 * r ≤ N) (v : Fin (n + 1) → ℤ)
    (hv : ∀ i, (1 ≤ v i ∧ v i ≤ (N : ℤ) ∧ v i ≠ (r : ℤ)) ∨ (N : ℤ) < v i)
    (hcard : (Finset.univ.filter (fun i : Fin (n + 1) => (N : ℤ) < v i)).card ≤ k) :
    1 / (N : ℝ) ≤ ML v :=
  ML_ge_robust_cop hk1 hr1 (copWin_le (copWin_all hk1 hk2 hN hr1 hr))
    (copWin_all hk1 hk2 hN hr1 hr) v hv hcard

/-- **Corollary S'(a), no hypothesis, \`1 ≤ k ≤ $KMAX\`, every \`N ≥ N*(k)\`.** -/
theorem cor_a_all {n k N : ℕ} (hk1 : 1 ≤ k) (hk2 : k ≤ $KMAX) (hN : NstarAll k ≤ N)
    (v : Fin (n + 1) → ℤ) (hpos : ∀ i, 1 ≤ v i)
    (hcard : (Finset.univ.filter (fun i : Fin (n + 1) => (N : ℤ) < v i)).card ≤ k)
    (hML : ML v < 1 / (N : ℝ)) :
    ∀ r : ℕ, 1 ≤ r → 2 * r ≤ N → ∃ i, v i = (r : ℤ) :=
  cor_a_cop hk1 (fun _ hr1 hr2 => copWin_all hk1 hk2 hN hr1 hr2) v hpos hcard hML

end Gap
end Sext6
end LRSpectrumFull
EOT
